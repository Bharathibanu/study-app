export const VOCABULARY = Object.freeze(entries.split('\n').map(line => {
  const [word, meaning] = line.split('|');
  return Object.freeze({id: word.toLowerCase(), word, meaning});
}));
export const WORDS_PER_DAY = 10;
export const VOCABULARY_CYCLE_DAYS = VOCABULARY.length / WORDS_PER_DAY;

// UTC arithmetic on a local calendar-date string avoids month resets and DST drift.
// A shared fixed anchor gives both devices the same set for the same calendar date.
export function dailyVocabulary(date) {
  if (typeof date !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error('Choose a valid vocabulary date.');
  const timestamp = Date.parse(date + 'T00:00:00Z');
  if (!Number.isFinite(timestamp) || new Date(timestamp).toISOString().slice(0,10) !== date) throw new Error('Choose a valid vocabulary date.');
  const ordinal = Math.floor(timestamp / 86400000);
  const setIndex = ((ordinal % VOCABULARY_CYCLE_DAYS) + VOCABULARY_CYCLE_DAYS) % VOCABULARY_CYCLE_DAYS;
  return {date, set: setIndex + 1, cycleDays: VOCABULARY_CYCLE_DAYS, words: VOCABULARY.slice(setIndex * WORDS_PER_DAY, (setIndex + 1) * WORDS_PER_DAY)};
}
